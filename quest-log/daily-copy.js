export function dailyCopy(now=new Date()) {
  const day=dayKey(now),index=Math.floor(Date.parse(day+'T00:00:00Z')/86400000);
  const pick=items=>items[((index%items.length)+items.length)%items.length];
  return {day,pages:Object.fromEntries(Object.entries(pages).map(([key,list])=>[key,pick(list)])),quote:pick(quotes),sideNote:pick(sideNotes),footer:pick(footers),dailyOpen:pick(dailyOpen),dailyClear:pick(dailyClear)};
}
